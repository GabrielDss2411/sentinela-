import type { FeatureCollection, Point } from 'geojson';
import { RJ_MUNICIPIOS } from './municipios';
import type { LngLat } from './routing';

export type HospitalType = 'hospital' | 'upa' | 'pronto-socorro' | 'maternidade';

export const HOSPITAL_TYPES: Record<HospitalType, { label: string; short: string; color: string }> = {
  hospital: { label: 'Hospital com emergência 24h', short: 'Hospital', color: '#e5484d' },
  'pronto-socorro': { label: 'Pronto-socorro', short: 'Pronto-socorro', color: '#f2711c' },
  upa: { label: 'UPA / Pronto atendimento 24h', short: 'UPA', color: '#2185d0' },
  maternidade: { label: 'Maternidade', short: 'Maternidade', color: '#a333c8' },
};

export type Hospital = {
  id: number;
  name: string;
  type: HospitalType;
  address: string;
  phone: string | null;
  sphere: string | null;
  /** Municipality name (from the IBGE code CNES provides). */
  city: string;
  coord: LngLat;
};

type Props = {
  cnes: number;
  nome: string;
  tipo: HospitalType;
  endereco: string;
  telefone: string | null;
  esfera: string | null;
  municipio: number;
};

/** Generated by scripts/fetch-hospitals.mjs from the CNES open data API. */
export async function loadHospitals(url = '/data/hospitais.geojson'): Promise<Hospital[]> {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`Falha ao carregar unidades de saúde (${res.status})`);
  const fc = (await res.json()) as FeatureCollection<Point, Props>;
  return fc.features.map((f) => ({
    id: f.properties.cnes,
    name: f.properties.nome,
    type: f.properties.tipo,
    address: f.properties.endereco,
    phone: f.properties.telefone,
    sphere: f.properties.esfera,
    city: RJ_MUNICIPIOS[f.properties.municipio] ?? 'Rio de Janeiro (estado)',
    coord: f.geometry.coordinates as LngLat,
  }));
}

/** Straight-line distance in meters. */
export function haversine(a: LngLat, b: LngLat) {
  const R = 6_371_000;
  const dLat = ((b[1] - a[1]) * Math.PI) / 180;
  const dLng = ((b[0] - a[0]) * Math.PI) / 180;
  const s = Math.sin(dLat / 2) ** 2 + Math.cos((a[1] * Math.PI) / 180) * Math.cos((b[1] * Math.PI) / 180) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(s));
}

/** Digits only, for tel: links. CNES phones come in many formats. */
export function telHref(phone: string) {
  const digits = phone.replace(/\D/g, '');
  return `tel:${digits.length === 10 || digits.length === 11 ? `+55${digits}` : digits}`;
}
